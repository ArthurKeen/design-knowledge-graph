#!/usr/bin/env python3
"""
scripts/analysis/token_savings_benchmark.py — quantifies the "10x token
reduction" claim in REQ-016 (business-requirements.md).

The constrained-retrieval architecture (embed question -> Golden Entity
anchor -> RESOLVED_TO reverse walk -> community peers -> chunk fetch ->
bounded context assembly, in src/graph_retriever.py) was real but unmeasured
— and, it turned out while wiring this benchmark up, partially broken (see
"Bugs fixed" below). Both are now fixed; this script measures the result.

Two comparisons are reported, because a true "naive vector RAG over the
whole corpus" baseline turned out to be uncomputable against the current
data (see below), and reporting a fabricated 0 for it would be worse than
not reporting it:

  - "chunk-truncation savings" (computed): the graph pipeline truncates each
    fetched doc-chunk excerpt to 400 chars (_format_context); this compares
    the actual assembled context against the same chunks at full length —
    i.e. exactly what the graph structure's compactness saves, holding the
    retrieval step fixed.
  - "naive full-corpus vector RAG" (attempted, currently N/A): embed the
    question, vector-search directly over every repo's {PREFIX}_Chunks
    collection with no graph constrainment, concatenate full chunk text.
    This is blocked: {PREFIX}_Chunks.embedding is null on every chunk in
    every repo (verified 2026-08 — 0/10 OR1200, 0/3 MOR1KX, 0/5 MAROCCHINO,
    0/51 IBEX have a populated embedding). Chunk-level embeddings were
    apparently never generated by the ingestion pipeline. Left wired up and
    reported as N/A rather than skipped, so re-running this script after
    that gap is closed elsewhere immediately produces the real number.

Bugs fixed in src/graph_retriever.py while building this benchmark (it had
apparently never been run successfully end-to-end against the live cluster):
  - No .env loading -> silently connected to localhost:8530/root/"" instead
    of the real cluster.
  - _build_retriever_from_env() imported config.ARANGO_HOST/ARANGO_DB/
    ARANGO_USER, none of which exist in config.py -> always ImportError,
    silently swallowed.
  - _AQL_EMBED_SEARCH and _word_fallback reused a `@@coll` collection-name
    bind parameter as a plain value (`_collection: @@coll`) -- this cluster
    rejects that with ERR 1568 "collection used as expression operand" (same
    AMP-planner family as the ERR 4 bug documented in cross_repo_bridge.py).
    Silently caught -> _anchor_lookup always returned zero hits.
  - _AQL_MENTIONED_IN traversed straight from a Golden Entity over
    MentionedIn edges, but those edges actually run Entities -> Chunks (raw,
    not golden) -- there is no direct edge. Needed the Consolidates hop.
    Also referenced non-existent fields (chunk.content, chunk.source_id,
    edge.frequency) instead of the real chunk.text/doc_basename.
  - _AQL_RESOLVED_TO referenced edge.match_method; the real field is
    edge.method.
Not fixed (documented, deferred — see sync_observations): community-peer
lookup assumes a `community` attribute directly on Golden Entities; real
community membership lives in a separate {PREFIX}_Communities.member_entities
array keyed to raw Entities, not Golden ones, so hit.community is always
None and _get_community_peers is dead code. Doesn't block this benchmark —
RTL nodes + doc chunks are the dominant content in the assembled context.

Usage:
    PYTHONPATH=src python3 scripts/analysis/token_savings_benchmark.py
"""
import datetime
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src"))

from graph_retriever import GraphRetriever  # noqa: E402

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                       "ic_analysis_output", "temporal_evolution")

BENCHMARK_QUESTIONS = [
    "What is the TLB flush mechanism?",
    "How does the Wishbone bus interface work?",
    "Explain the finite state machine controlling exception handling.",
    "What is the data cache write-back policy?",
    "How is the program counter updated during a branch?",
    "What registers hold the processor's exception state?",
]

_NAIVE_CHUNK_SEARCH = """
FOR doc IN @@coll
    FILTER doc.embedding != null
    LET score = (
        FOR i IN 0..LENGTH(doc.embedding)-1
            COLLECT AGGREGATE s = SUM(doc.embedding[i] * @qvec[i])
            RETURN s
    )[0]
    SORT score DESC
    LIMIT @top_k
    RETURN MERGE(doc, {_score: score})
"""


def _tokenizer():
    try:
        import tiktoken
        enc = tiktoken.get_encoding("cl100k_base")
        return lambda text: len(enc.encode(text)), "tiktoken/cl100k_base"
    except ImportError:
        return lambda text: round(len(text.split()) * 1.3), "word-count heuristic (~1.3 tok/word)"


def full_chunk_context(hits) -> str:
    """The same doc_chunks the graph pipeline actually fetched, at full
    (untruncated) length instead of _format_context's 400-char cutoff —
    isolates what that truncation alone saves, holding retrieval fixed."""
    parts = []
    for hit in hits:
        for c in hit.doc_chunks:
            parts.append(f"[{c.get('source', '?')}] {c.get('content', '')}")
    return "\n\n".join(parts)


def naive_vector_baseline(retriever: GraphRetriever, question: str, top_k: int):
    """Returns (text, usable). usable=False means every candidate collection
    has zero populated embeddings, i.e. the comparison is uncomputable with
    current data rather than genuinely empty."""
    qvec = retriever._embed(question)
    candidates = []
    any_embedded_chunks = False
    for repo in retriever.repos:
        coll = f"{repo}_Chunks"
        if not retriever._db.has_collection(coll):
            continue
        if list(retriever._db.aql.execute(
                "FOR d IN @@c FILTER d.embedding != null LIMIT 1 RETURN 1",
                bind_vars={"@c": coll})):
            any_embedded_chunks = True
        rows = list(retriever._db.aql.execute(
            _NAIVE_CHUNK_SEARCH, bind_vars={"@coll": coll, "qvec": qvec, "top_k": top_k}))
        candidates.extend(rows)
    if not any_embedded_chunks:
        return "", False
    candidates.sort(key=lambda d: d.get("_score", 0), reverse=True)
    top = candidates[:top_k]
    parts = [f"[{c.get('doc_basename', c.get('_id'))}] {c.get('text', '')}" for c in top]
    return "\n\n".join(parts), True


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    count_tokens, tokenizer_label = _tokenizer()

    print("[token-benchmark] connecting to live retriever …")
    retriever = GraphRetriever()
    retriever.llm_fn = None  # --no-llm equivalent: constructor's llm_fn=None means
                             # "auto-detect", so disabling requires this post-hoc
                             # override — same pattern graph_retriever.py's own
                             # CLI uses for --no-llm.

    rows = []
    naive_usable = None
    for q in BENCHMARK_QUESTIONS:
        print(f"[token-benchmark] {q!r}")
        graph_result = retriever.query(q, verbose=False)
        graph_tokens = count_tokens(graph_result.context_text)

        full_tokens = count_tokens(full_chunk_context(graph_result.golden_hits))
        trunc_ratio = round(full_tokens / graph_tokens, 2) if graph_tokens and full_tokens else None

        naive_text, usable = naive_vector_baseline(retriever, q, top_k=retriever.top_k_golden)
        naive_usable = usable if naive_usable is None else (naive_usable or usable)
        naive_tokens = count_tokens(naive_text) if usable else None
        naive_ratio = round(naive_tokens / graph_tokens, 2) if (usable and graph_tokens and naive_tokens) else None

        rows.append({
            "question": q, "graph_tokens": graph_tokens,
            "full_chunk_tokens": full_tokens, "trunc_reduction_x": trunc_ratio,
            "naive_tokens": naive_tokens, "naive_reduction_x": naive_ratio,
        })
        print(f"    graph={graph_tokens} tok · full-chunks={full_tokens} tok ({trunc_ratio}x) "
              f"· naive-vector-RAG={'N/A (no chunk embeddings)' if not usable else f'{naive_tokens} tok ({naive_ratio}x)'}")

    avg_trunc = round(sum(r["trunc_reduction_x"] for r in rows if r["trunc_reduction_x"]) / len(rows), 2)

    lines = [
        "# Token Savings Benchmark (REQ-016)\n",
        f"*Generated: {datetime.datetime.utcnow().isoformat()}Z*  ·  tokenizer: {tokenizer_label}\n",
        "See module docstring for the exact methodology, the bugs discovered and fixed "
        "in src/graph_retriever.py to make this pipeline actually runnable, and why the "
        "naive-full-corpus-vector-RAG comparison is currently N/A.\n",
        "| Question | Graph-constrained tokens | Full-chunk tokens (no truncation) | "
        "Truncation saves | Naive vector-RAG tokens |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {r['question']} | {r['graph_tokens']} | {r['full_chunk_tokens']} | "
        f"{r['trunc_reduction_x']}x | {'N/A' if r['naive_tokens'] is None else r['naive_tokens']} |"
        for r in rows
    ]
    lines.append(f"\n**Average truncation-only reduction: {avg_trunc}x** across {len(rows)} questions.")
    if not naive_usable:
        lines.append(
            "\n**Naive full-corpus vector-RAG baseline: N/A.** Every repo's `{PREFIX}_Chunks` "
            "collection has zero chunks with a populated `embedding` field — chunk-level "
            "embeddings were apparently never generated by the ingestion pipeline (Golden "
            "Entity embeddings ARE populated; this gap is specific to raw chunks). The "
            "'10x reduction vs. naive RAG' claim in REQ-016 cannot be measured until that's "
            "closed. This script is wired up to compute it automatically the moment it is."
        )
    lines.append(
        "\nNote: token count alone doesn't capture that the graph-constrained context is "
        "also more *targeted* (RTL cross-references, cross-repo analogues) than raw chunk "
        "text of the same size would be — this measures context-assembly size, not answer "
        "quality."
    )

    out_path = os.path.join(OUT_DIR, "token_savings_benchmark.md")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\n[token-benchmark] wrote {out_path}")
    print(f"[token-benchmark] avg truncation-only reduction: {avg_trunc}x · "
          f"naive-vector-RAG baseline usable: {naive_usable}")


if __name__ == "__main__":
    main()
